    // ── Self-verification: dual-assertion tests ──
    // For each language: generated match scaffold with ALL variants → scan_matches → 0 hits
    // AND with ONE variant removed → scan_matches → 1 hit naming the missing variant

    use crate::language::MatchHit;
    use std::collections::HashSet;

    fn variants() -> Vec<String> {
        vec![
            "Pending".to_string(),
            "Confirmed".to_string(),
            "Shipped".to_string(),
            "Delivered".to_string(),
            "Cancelled".to_string(),
        ]
    }

    fn build_indices(
        union_name: &str,
        variants: &[String],
    ) -> (
        std::collections::HashMap<String, (String, HashSet<String>)>,
        std::collections::HashMap<String, HashSet<String>>,
    ) {
        let variant_set: HashSet<String> = variants.iter().cloned().collect();
        let mut vi = std::collections::HashMap::new();
        for v in variants {
            vi.insert(v.clone(), (union_name.to_string(), variant_set.clone()));
        }
        let mut um = std::collections::HashMap::new();
        um.insert(union_name.to_string(), variant_set);
        (vi, um)
    }

    fn self_verify(lang_name: &str) {
        let registry = LangRegistry::new();
        let lang = registry.for_name(lang_name).unwrap();
        let all_variants = variants();
        let gen_match = lang.generate_match_scaffold.unwrap();
        let (vi, um) = build_indices("OrderStatus", &all_variants);

        // Assertion 1: all variants → 0 hits
        let full_scaffold = gen_match("OrderStatus", &all_variants);
        let mut hits: Vec<MatchHit> = Vec::new();
        (lang.scan_matches)(&full_scaffold, "test", &vi, &um, &mut hits);
        assert!(
            hits.is_empty(),
            "[{lang_name}] full scaffold should produce 0 hits, got {}: {:?}",
            hits.len(),
            hits.iter().map(|h| &h.missing_variants).collect::<Vec<_>>()
        );

        // Assertion 2: remove last variant → 1 hit naming "Cancelled"
        let partial: Vec<String> = all_variants[..4].to_vec();
        let partial_scaffold = gen_match("OrderStatus", &partial);
        let mut hits2: Vec<MatchHit> = Vec::new();
        (lang.scan_matches)(&partial_scaffold, "test", &vi, &um, &mut hits2);
        assert_eq!(
            hits2.len(),
            1,
            "[{lang_name}] partial scaffold should produce 1 hit, got {}",
            hits2.len()
        );
        assert!(
            hits2[0].missing_variants.contains(&"Cancelled".to_string()),
            "[{lang_name}] missing variants should include 'Cancelled', got {:?}",
            hits2[0].missing_variants
        );
    }

